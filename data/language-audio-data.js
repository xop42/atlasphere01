/**
 * Resolves the best language audio sample for any country based on ISO code,
 * explicit country languages string, or continent fallback.
 */
window.getLanguageAudioForCountry = function (iso_a3, continent, countryName, languagesStr) {
  const dict = window.LANGUAGE_AUDIO_DATA;
  if (!dict) return null;

  // 1. Check exact ISO-A3 match
  if (iso_a3 && dict[iso_a3]) {
    return dict[iso_a3];
  }

  // 2. Check by country languages string (e.g. "French, German" -> matches "french")
  if (languagesStr && typeof languagesStr === 'string' && dict.languages) {
    const tokens = languagesStr.toLowerCase().split(/[\s,;/]+/);
    for (let t of tokens) {
      t = t.trim();
      if (t && dict.languages[t]) {
        return dict.languages[t];
      }
    }
  }

  // 3. Check by continent region fallback
  if (continent && dict.regions && dict.regions[continent]) {
    return dict.regions[continent];
  }

  // 4. Default fallback
  return dict.regions["Europe"];
};
